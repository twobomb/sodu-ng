const GENDER_IDX = { m: 0, f: 1, n: 2, pl: 3 };

function decline(masc) {
    if (masc.endsWith('ий')) {
        const stem = masc.slice(0, -2);
        if (/[кгхжшчщ]$/.test(stem)) return [masc, stem + 'ая', stem + 'ое', stem + 'ие'];
        return [masc, stem + 'яя', stem + 'ее', stem + 'ие'];
    }
    if (masc.endsWith('ый') || masc.endsWith('ой')) {
        const stem = masc.slice(0, -2);
        return [masc, stem + 'ая', stem + 'ое', stem + 'ые'];
    }
    return [masc, masc, masc, masc];
}

const ADJ = ADJ_M.map(decline);
const NOUNS = NOUNS_SRC.trim().split(',').map((s) => {
    const i = s.indexOf(':');
    return { w: s.slice(0, i).trim(), g: s.slice(i + 1).trim() };
});
const N_ADJ = ADJ.length;
const N_NOUN = NOUNS.length;
const N_NUM = 90; // 10..99
const TOTAL = N_ADJ * N_NOUN * N_NUM;

// ---------- FEISTEL-ПЕРЕСТАНОВКА ----------
// Находим делитель рядом с sqrt(TOTAL) для разбиения [0, TOTAL) = H1 × H2
function nearestFactor(N2) {
    const s = Math.floor(Math.sqrt(N2));
    for (let h = s; h >= 1; h--) if (N2 % h === 0) return h;
    return 1;
}
const H1 = nearestFactor(TOTAL);
const H2 = TOTAL / H1;

// Раундовая функция — быстрый 32-битный микс
function hashRound(x, i) {
    let h = Math.imul((x + i * 0x9E3779B9) | 0, 0x85EBCA6B);
    h ^= h >>> 13;
    h = Math.imul(h, 0xC2B2AE35);
    h ^= h >>> 16;
    return h >>> 0;
}

// Биекция на [0, H1*H2)
function permute(x) {
    let L = x % H1;
    let R = (x - L) / H1;
    for (let i = 0; i < 8; i++) {
        if (i % 2 === 0) {
            R = (R + (hashRound(L, i) % H2)) % H2;
        } else {
            L = (L + (hashRound(R, i) % H1)) % H1;
        }
    }
    return L + R * H1;
}

/**
 * Детерминированный идентификатор вызова с обёрткой диапазона.
 * @param {number} num — целое ≥ 1, без верхней границы
 * @returns {string} например "тихая-лиса-42" или "тихая-лиса-42-1"
 */
function generateCallId(num) {
    if (!Number.isInteger(num) || num < 1) {
        throw new RangeError('num должен быть целым положительным числом');
    }

    const cycle = Math.floor((num - 1) / TOTAL); // 0, 1, 2, ...
    const base = ((num - 1) % TOTAL) + 1; // 1..TOTAL

    const z = permute(base - 1);

    const numIdx = z % N_NUM;
    const rest = (z - numIdx) / N_NUM;
    const nounIdx = rest % N_NOUN;
    const adjIdx = (rest - nounIdx) / N_NOUN;

    const noun = NOUNS[nounIdx];
    const form = ADJ[adjIdx][GENDER_IDX[noun.g]];

    const code = `${form}-${noun.w}-${10 + numIdx}`;
    return cycle === 0 ? code : `${code}${cycle}`;
}

