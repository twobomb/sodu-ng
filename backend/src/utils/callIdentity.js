// Гарантируем словесный идентификатор и цвет для вызова.
// Сохраняет уже записанные значения, для старых записей вычисляет на лету.
// ============================================================
const decorateCall = (call) => {
    if (!call) return call;
    const n = Number(call.number);
    const ok = Number.isInteger(n) && n >= 1;
    if (ok && (!call.call_code || !call.color)) {
        call.call_code = generateCallId(n);
        call.color = colorFor(n);
    }
    return call;
};

