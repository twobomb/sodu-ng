// ---------- ЦВЕТ ----------
// HSL → HEX
function hslToHex(h, s, l) {
    l /= 100;
    const a = (s * Math.min(l, 1 - l)) / 100;
    const f = (n) => {
        const k = (n + h / 30) % 12;
        const c = l - a * Math.max(Math.min(k - 3, 9 - k, 1), -1);
        return Math.round(255 * c).toString(16).padStart(2, '0');
    };
    return `#${f(0)}${f(8)}${f(4)}`;
}

// 24 цвета, равномерно по кругу тонов (0°, 15°, 30°, …, 345°)
const PALETTE = Array.from({ length: 24 }, (_, i) => hslToHex(i * 15, 78, 52));

const N = PALETTE.length; // 24
const STEP = 5; // gcd(5, 24) = 1 → сдвиг на 75° между соседями

/**
 * Детерминированный цвет по числу.
 * @param {number} num — целое ≥ 1
 * @returns {string} HEX-цвет, например "#e6194b"
 */
function colorFor(num) {
    if (!Number.isInteger(num) || num < 1) {
        throw new RangeError('num должен быть целым положительным числом');
    }
    const i = ((num - 1) * STEP) % N;
    return PALETTE[i];
}

