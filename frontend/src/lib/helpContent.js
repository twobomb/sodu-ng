/** Приводит строку к виду, удобному для поиска (регистр и «ё» не важны). */
export const normalizeHelpText = (value) =>
    String(value ?? '').toLowerCase().replace(/ё/g, 'е');

/** Плоский текст блока — участвует в поиске. */
const blockToPlainText = (block) => {
    const parts = [block.title, block.text, block.note];
    if (Array.isArray(block.items)) {
        for (const item of block.items) {
            if (typeof item === 'string') parts.push(item);
            else if (item) parts.push(item.name, item.description, item.label);
        }
    }
    return parts.filter(Boolean).join(' ');
};

/**
 * Ищет запрос по справке.
 * Возвращает массив { section, blockIds, score } в порядке релевантности.
 * blockIds === null — совпал раздел целиком, показываем все его блоки.
 */
export const searchHelp = (sections, rawQuery) => {
    const query = normalizeHelpText(rawQuery).trim();

    if (!query) {
        return sections.map((section) => ({ section, blockIds: null, score: 0 }));
    }

    const results = [];

    for (const section of sections) {
        let score = 0;
        const blockIds = [];

        if (normalizeHelpText(section.title).includes(query)) score += 100;
        if (normalizeHelpText(section.summary).includes(query)) score += 40;
        if ((section.tags || []).some((tag) => normalizeHelpText(tag).includes(query))) score += 30;

        for (const block of section.blocks) {
            const titleHit = block.title ? normalizeHelpText(block.title).includes(query) : false;
            const textHit = normalizeHelpText(blockToPlainText(block)).includes(query);
            if (titleHit || textHit) {
                blockIds.push(block.id);
                score += titleHit ? 25 : 15;
            }
        }

        if (score > 0) {
            results.push({ section, blockIds: blockIds.length ? blockIds : null, score });
        }
    }

    return results.sort((a, b) => b.score - a.score);
};

/** Разбивает текст на части, помечая совпадения с запросом (для подсветки). */
export const splitByQuery = (text, rawQuery) => {
    const source = String(text ?? '');
    const query = normalizeHelpText(rawQuery).trim();

    if (!query || !source) return [{ text: source, match: false }];

    // Регистр и «ё» не меняют длину строки, поэтому индексы совпадают
    const haystack = normalizeHelpText(source);
    const parts = [];
    let from = 0;

    while (from < source.length) {
        const at = haystack.indexOf(query, from);
        if (at === -1) {
            parts.push({ text: source.slice(from), match: false });
            break;
        }
        if (at > from) parts.push({ text: source.slice(from, at), match: false });
        parts.push({ text: source.slice(at, at + query.length), match: true });
        from = at + query.length;
    }

    return parts;
};

/** Сколько блоков совпало (для счётчика под поиском). */
export const countHelpMatches = (results) =>
    results.reduce(
        (sum, result) =>
            sum + (result.blockIds ? result.blockIds.length : result.section.blocks.length),
        0
    );

/** Доступен ли раздел пользователю (permissions — «любое из», пустой список — всем). */
export const isHelpSectionAvailable = (section, hasPermission) => {
    if (!section.permissions?.length) return true;
    return section.permissions.some((permission) => hasPermission(permission));
};

