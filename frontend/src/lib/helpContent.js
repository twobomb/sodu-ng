/**
 * Содержимое раздела «Справка».
 *
 * Каждый раздел:
 *   id          — якорь (#help-<id>), он же ключ для оглавления;
 *   title       — название раздела (как в меню системы);
 *   icon        — иконка lucide-react;
 *   accent      — цветовой акцент (ключ из HELP_ACCENTS);
 *   route       — маршрут раздела, если у пользователя есть доступ;
 *   permissions — любое из прав даёт доступ к разделу (нет поля — доступно всем);
 *   summary     — краткое описание (в шапке статьи и в поиске);
 *   tags        — дополнительные ключевые слова для поиска;
 *   blocks      — блоки статьи:
 *                 'text'   { text }
 *                 'list'   { items: [строка, ...] }        — маркированный список
 *                 'steps'  { items: [строка, ...] }        — нумерованный список
 *                 'note'   { tone: 'info'|'tip'|'warn'|'success', text }
 *                 'fields' { items: [{ name, description }] } — таблица «поле — описание»
 *
 * Чтобы поправить текст справки — правьте ТОЛЬКО этот файл.
 */

